"""Bundle non-Python assets into fpb/_embedded.py.

marimo's WebAssembly export ships only .py files, so the widget JS/CSS, the tax
tables, and the example plan are embedded as Python strings. Run after editing
any of those files:

    python scripts/embed_assets.py

tests/test_embedded.py fails if the bundle is out of date.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def render() -> str:
    esm = (ROOT / "fpb/ui/timeline.js").read_text(encoding="utf-8")
    css = (ROOT / "fpb/ui/timeline.css").read_text(encoding="utf-8")
    tax = {
        p.name: p.read_text(encoding="utf-8")
        for p in sorted((ROOT / "fpb/tax/data").glob("us_federal_*.yaml"))
    }
    plan = (ROOT / "plans/example.yaml").read_text(encoding="utf-8")
    return "\n".join([
        '"""Generated by scripts/embed_assets.py. Do not edit by hand."""',
        "",
        f"TIMELINE_ESM = {esm!r}",
        "",
        f"TIMELINE_CSS = {css!r}",
        "",
        f"TAX_TABLES = {tax!r}",
        "",
        f"EXAMPLE_PLAN = {plan!r}",
        "",
    ])


if __name__ == "__main__":
    (ROOT / "fpb/_embedded.py").write_text(render(), encoding="utf-8")
    print("wrote fpb/_embedded.py")
